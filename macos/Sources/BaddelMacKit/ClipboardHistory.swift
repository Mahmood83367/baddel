import AppKit
import Foundation

protocol ClipboardBuffer: AnyObject {
    var changeCount: Int { get }
    var clipboardTypes: [NSPasteboard.PasteboardType] { get }
    @discardableResult func clearContents() -> Int
    func string(forType dataType: NSPasteboard.PasteboardType) -> String?
    func data(forType dataType: NSPasteboard.PasteboardType) -> Data?
    func setString(_ string: String, forType dataType: NSPasteboard.PasteboardType) -> Bool
    func setData(_ data: Data?, forType dataType: NSPasteboard.PasteboardType) -> Bool
    func readFileURLs() -> [URL]
    func writeFileURLs(_ urls: [URL]) -> Bool
}

extension NSPasteboard: ClipboardBuffer {
    var clipboardTypes: [NSPasteboard.PasteboardType] { pasteboardItems?.flatMap(\.types) ?? [] }

    func readFileURLs() -> [URL] {
        readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
    }

    func writeFileURLs(_ urls: [URL]) -> Bool { writeObjects(urls.map { $0 as NSURL }) }
}

public struct ClipboardEntry: Codable, Identifiable {
    public enum Content: Codable {
        case text(String)
        case image(file: String, type: String)
        case files(originals: [String], copies: [String]?)
    }

    public let id: UUID
    public let date: Date
    public var content: Content

    public var title: String {
        switch content {
        case .text(let value):
            return value.components(separatedBy: .newlines).joined(separator: " ")
        case .image:
            return "Image"
        case .files(let originals, _):
            return originals.map { URL(fileURLWithPath: $0).lastPathComponent }.joined(separator: ", ")
        }
    }

    public var isPinned: Bool {
        if case .files(_, let copies) = content { return copies != nil }
        return false
    }
}

/// Local history of user-initiated copy operations. A file entry retains its
/// source path until the user explicitly saves a copy.
public final class ClipboardHistory {
    public enum AccessError: LocalizedError {
        case unavailableFile
        case unavailableItem
        case couldNotCopy

        public var errorDescription: String? {
            switch self {
            case .unavailableFile: return "An original file is missing or unavailable."
            case .unavailableItem: return "This clipboard item is no longer available."
            case .couldNotCopy: return "The clipboard could not be updated."
            }
        }
    }

    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]
    private let root: URL
    private let pasteboard: ClipboardBuffer
    private let files = FileManager.default
    private let maxHistory = 100
    private let maxImageBytes = 8 * 1024 * 1024
    private let maxTextBytes = 256 * 1024
    private let maxStoredImageBytes = 64 * 1024 * 1024
    private var lastChange: Int
    private var timer: Timer?

    public private(set) var entries: [ClipboardEntry] = []
    public var onChange: (() -> Void)?

    public convenience init(directory: URL) {
        self.init(directory: directory, pasteboard: NSPasteboard.general)
    }

    init(directory: URL, pasteboard: ClipboardBuffer) {
        root = directory
        self.pasteboard = pasteboard
        lastChange = pasteboard.changeCount
        if let data = try? Data(contentsOf: directory.appendingPathComponent("history.json")),
           let previous = try? JSONDecoder().decode([ClipboardEntry].self, from: data) {
            entries = previous
        }
    }

    deinit { timer?.invalidate() }

    public func setRecording(_ enabled: Bool) {
        timer?.invalidate()
        timer = nil
        lastChange = pasteboard.changeCount
        guard enabled else { return }
        let poller = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.captureIfChanged()
        }
        RunLoop.main.add(poller, forMode: .common)
        timer = poller
    }

    public func captureIfChanged() {
        let change = pasteboard.changeCount
        guard change != lastChange else { return }
        lastChange = change
        guard Self.ignoredTypes.isDisjoint(with: pasteboard.clipboardTypes) else { return }

        let id = UUID()
        let content: ClipboardEntry.Content
        var newImage: URL?
        let urls = pasteboard.readFileURLs()
        if !urls.isEmpty {
            let paths = urls.map(\.path)
            if case .files(let originals, _) = entries.first?.content, originals == paths { return }
            content = .files(originals: paths, copies: nil)
        } else if let (type, data) = ([NSPasteboard.PasteboardType.png, .tiff].lazy.compactMap { type in
            self.pasteboard.data(forType: type).map { (type, $0) }
        }.first), !data.isEmpty, data.count <= maxImageBytes {
            if case .image(let file, _) = entries.first?.content,
               (try? Data(contentsOf: root.appendingPathComponent(file))) == data { return }
            let file = id.uuidString + (type == .png ? ".png" : ".tiff")
            let url = root.appendingPathComponent(file)
            do {
                try makeRoot()
                try data.write(to: url, options: .atomic)
            } catch { return }
            newImage = url
            content = .image(file: file, type: type.rawValue)
        } else if let value = pasteboard.string(forType: .string),
                  !value.isEmpty, value.utf8.count <= maxTextBytes {
            if case .text(let previous) = entries.first?.content, previous == value { return }
            content = .text(value)
        } else {
            return
        }

        // A newer copy may arrive while a source app is providing its data.
        guard pasteboard.changeCount == change else {
            if let newImage { try? files.removeItem(at: newImage) }
            return
        }
        var next = entries
        next.insert(ClipboardEntry(id: id, date: Date(), content: content), at: 0)
        next = pruned(next)
        do { try commit(next) }
        catch { if let newImage { try? files.removeItem(at: newImage) } }
    }

    public func image(for entry: ClipboardEntry) -> NSImage? {
        guard case .image(let file, _) = entry.content else { return nil }
        return NSImage(contentsOf: root.appendingPathComponent(file))
    }

    public func restore(_ entry: ClipboardEntry) throws {
        switch entry.content {
        case .text(let text):
            pasteboard.clearContents()
            guard pasteboard.setString(text, forType: .string) else { throw AccessError.couldNotCopy }
        case .image(let file, let type):
            guard let image = try? Data(contentsOf: root.appendingPathComponent(file)) else {
                throw AccessError.unavailableItem
            }
            pasteboard.clearContents()
            guard pasteboard.setData(image, forType: .init(type)) else { throw AccessError.couldNotCopy }
        case .files(let originals, let copies):
            let urls = copies?.map { root.appendingPathComponent($0) }
                ?? originals.map { URL(fileURLWithPath: $0) }
            guard urls.allSatisfy({ files.fileExists(atPath: $0.path) }) else { throw AccessError.unavailableFile }
            pasteboard.clearContents()
            guard pasteboard.writeFileURLs(urls) else { throw AccessError.couldNotCopy }
        }
        lastChange = pasteboard.changeCount
    }

    public func pin(_ entry: ClipboardEntry) throws {
        guard let index = entries.firstIndex(where: { $0.id == entry.id }),
              case .files(let originals, nil) = entries[index].content else { throw AccessError.unavailableItem }
        let relative = "pinned-" + entry.id.uuidString
        let directory = root.appendingPathComponent(relative, isDirectory: true)
        var paths: [String] = []
        var createdDirectory = false
        do {
            try makeRoot()
            try files.createDirectory(at: directory, withIntermediateDirectories: false, attributes: [.posixPermissions: 0o700])
            createdDirectory = true
            for (position, original) in originals.enumerated() {
                let source = URL(fileURLWithPath: original).resolvingSymlinksInPath()
                guard files.fileExists(atPath: source.path) else { throw AccessError.unavailableFile }
                let name = URL(fileURLWithPath: original).lastPathComponent
                let parent = directory.appendingPathComponent(String(position), isDirectory: true)
                try files.createDirectory(at: parent, withIntermediateDirectories: false)
                try files.copyItem(at: source, to: parent.appendingPathComponent(name))
                paths.append("\(relative)/\(position)/\(name)")
            }
            var next = entries
            next[index].content = .files(originals: originals, copies: paths)
            try commit(next)
        } catch {
            if createdDirectory { try? files.removeItem(at: directory) }
            throw error
        }
    }

    public func remove(_ entry: ClipboardEntry) throws {
        try commit(entries.filter { $0.id != entry.id })
    }

    public func clearRecent() throws {
        try commit(entries.filter(\.isPinned))
    }

    private func makeRoot() throws {
        try files.createDirectory(at: root, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
    }

    private func pruned(_ items: [ClipboardEntry]) -> [ClipboardEntry] {
        var imageBytes = 0
        var recentCount = 0
        return items.filter { entry in
            if entry.isPinned { return true }
            guard recentCount < maxHistory else { return false }
            if case .image(let file, _) = entry.content {
                let size = (try? root.appendingPathComponent(file).resourceValues(forKeys: [.fileSizeKey]).fileSize) ?? 0
                guard imageBytes + size <= maxStoredImageBytes else { return false }
                imageBytes += size
            }
            recentCount += 1
            return true
        }
    }

    private func commit(_ next: [ClipboardEntry]) throws {
        try makeRoot()
        let data = try JSONEncoder().encode(next)
        try data.write(to: root.appendingPathComponent("history.json"), options: .atomic)
        let previous = entries
        entries = next
        let keep = Set(next.map(\.id))
        for entry in previous where !keep.contains(entry.id) {
            if case .image(let file, _) = entry.content {
                try? files.removeItem(at: root.appendingPathComponent(file))
            }
            if entry.isPinned {
                try? files.removeItem(at: root.appendingPathComponent("pinned-" + entry.id.uuidString))
            }
        }
        onChange?()
    }
}
